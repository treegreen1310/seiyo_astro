export const isLearnable = (key: string): boolean => key in PLANET_LEARN;

export type SentencePart = { text: string; kind?: 'planet' | 'sign' | 'house' };

// 「天体（何が）× サイン（どのように）× ハウス（どこで）」の組み立て文
// 部品ごとに色分けして表示できるよう、パーツの配列で返す
export const buildReadingSentence = (key: string, sign: string, house: number): SentencePart[] | null => {
  const p = PLANET_LEARN[key];
  const s = SIGN_LEARN[sign];
  if (!p || !s) return null;
  const head: SentencePart[] = [
    { text: 'あなたの' },
    { text: `${p.role}（${p.name}）`, kind: 'planet' },
    { text: 'は、' },
    { text: `${s.style}スタイル（${s.name}）`, kind: 'sign' },
  ];
  if (!p.usesHouse) {
    return [...head, { text: `で${p.verb}。` }];
  }
  const h = HOUSE_LEARN[house];
  if (!h) return null;
  return [
    ...head,
    { text: 'で、' },
    { text: `「${h.field}」の場面`, kind: 'house' },
    { text: `で${p.verb}。` },
  ];
};
